import { NextRequest, NextResponse } from "next/server";
import { pocketFi } from "@/lib/pocketfi/client";
import { isSupabaseAdminConfigured, supabaseAdmin } from "@/lib/supabase/admin";
import { requireUser } from "@/lib/auth/server-auth";
import { checkRateLimit } from "@/lib/security/rate-limit";

export const runtime = "nodejs";

/**
 * Direct Wallet Funding API (PocketFi)
 * Endpoint: POST /api/wallet/fund
 * Security: Requires authenticated user session
 */
export async function POST(request: NextRequest) {
  try {
    const auth = await requireUser(request);
    if (!auth.authorized) {
      return auth.errorResponse!;
    }

    // Rate limit: Max 10 fund requests per minute
    const rateCheck = checkRateLimit(request, 10, 60 * 1000);
    if (!rateCheck.allowed) {
      return NextResponse.json(
        {
          status: false,
          message: "Too many deposit attempts. Please wait a moment.",
        },
        { status: 429 },
      );
    }

    const body = await request.json();
    const amount = Number(body.amount);

    if (!amount || isNaN(amount) || amount < 10) {
      return NextResponse.json(
        { status: false, message: "Minimum deposit amount is ₦10" },
        { status: 400 },
      );
    }

    const userId = auth.user!.id;
    const userEmail = auth.user!.email || "advertiser@adision.xyz";

    // Fetch the full Supabase user to read their saved name
    let userName = "";

    if (isSupabaseAdminConfigured()) {
      const { data } = await supabaseAdmin.auth.admin.getUserById(userId);
      const meta = data?.user?.user_metadata || {};

      userName =
        meta.full_name ||
        meta.name ||
        [meta.first_name, meta.last_name].filter(Boolean).join(" ") ||
        "";

      // Fallback: profiles table (change table/column to match yours)
      if (!userName) {
        const { data: profile } = await supabaseAdmin
          .from("profiles")
          .select("full_name")
          .eq("id", userId)
          .maybeSingle();
        userName = profile?.full_name || "";
      }
    }

    // Last resort: part of the email before the @
    if (!userName) {
      userName = userEmail.split("@")[0];
    }

    // 1. Generate unique deposit reference
    const reference = `wlt_${Date.now()}_${Math.random().toString(36).substring(2, 8)}`;

    const appBaseUrl = process.env.NEXT_PUBLIC_APP_URL || "https://adision.xyz";
    const checkoutSession = await pocketFi.createCheckoutSession({
      amount,
      email: userEmail,
      name: userName,
      reference,
      redirectUrl: `${appBaseUrl}/advertiser`,
    });

    // Extract the virtual account generated by PocketFi for this checkout session
    const pocketFiAccount = checkoutSession.virtualAccount;

    const virtualAccount = pocketFiAccount
      ? {
          ...pocketFiAccount,
          // Sandbox returns "sandbox" as the name, so show the user's name while testing
          account_name:
            process.env.NODE_ENV !== "production" &&
            String(pocketFiAccount.account_name).toLowerCase() === "sandbox"
              ? userName
              : pocketFiAccount.account_name,
        }
      : {
          bank_name: "SafeHaven MFB",
          account_number:
            checkoutSession.paymentId?.replace(/^PFI\|/, "") || "",
          account_name: userName,
          expiry_time: new Date(Date.now() + 60 * 60 * 1000).toISOString(),
          amount,
          reference,
        };
    // 3. Ensure user has a wallet record and log pending transaction
    if (isSupabaseAdminConfigured()) {
      let { data: wallet } = await supabaseAdmin
        .from("wallets")
        .select("id, available_balance")
        .eq("user_id", userId)
        .maybeSingle();

      if (!wallet) {
        const { data: newW } = await supabaseAdmin
          .from("wallets")
          .insert({
            user_id: userId,
            available_balance: 0,
            pending_balance: 0,
            currency: "NGN",
          })
          .select("id, available_balance")
          .single();
        wallet = newW;
      }

      if (wallet && checkoutSession.paymentId) {
        await supabaseAdmin.from("ledger_transactions").insert({
          wallet_id: wallet.id,
          user_id: userId,
          transaction_type: "DEPOSIT",
          amount,
          direction: "CREDIT",
          balance_after: Number(wallet.available_balance || 0),
          reference_type: "POCKETFI_DEPOSIT",
          description: `PocketFi payment ID: ${checkoutSession.paymentId} | Ref: ${reference}`,
          status: "PENDING",
        });
      }
    }

    return NextResponse.json({
      status: true,
      data: {
        reference,
        amount,
        payment_link: checkoutSession.paymentLink,
        payment_id: checkoutSession.paymentId,
        virtual_account: virtualAccount,
      },
    });
  } catch (error: any) {
    console.error("[Wallet Fund Error]:", error);
    return NextResponse.json(
      {
        status: false,
        message: error.message || "Failed to initiate wallet deposit",
      },
      { status: 500 },
    );
  }
}
